#!/usr/bin/env node
// Writes docs/API.md: every route in the server modules, with the comment just above it. Run after adding routes.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const files = fs.readdirSync(ROOT).filter((f) => f.endsWith('.js')).sort((a, b) => (a === 'server.js' ? -1 : b === 'server.js' ? 1 : a.localeCompare(b)));
let out = '# Nimbus API\n\nGenerated by `node bin/api-docs.mjs` from the route() calls in the server modules. All routes need a login\n(session cookie) unless noted; changes must be sent as JSON. `/api/hook/*` routes are for bots during a run\n(header `x-nimbus-hook`). `bin/nimbus.mjs <METHOD> <path> [json]` calls any of them from the server.\n';
for (const f of files) {
  const lines = fs.readFileSync(path.join(ROOT, f), 'utf8').split('\n'), rows = [];
  lines.forEach((l, i) => {
    const m = l.match(/route\('(GET|POST|PUT|PATCH|DELETE)',\s*'([^']+)'/); if (!m) return;
    let note = '', j = i - 1;
    while (j >= 0 && /^\s*\/\//.test(lines[j])) { note = lines[j].replace(/^\s*\/\/\s?/, '') + ' ' + note; j--; }
    if (!note) { const c = l.match(/\/\/\s*(.+)$/); if (c) note = c[1]; }
    note = note.replace(/-{3,}[^-]*-{3,}/g, '');
    rows.push(`| ${m[1]} | \`${m[2]}\` | ${note.trim().replace(/\|/g, '\\|').slice(0, 220)} |`);
  });
  if (rows.length) out += `\n## ${f}\n\n| Method | Path | What it does |\n|---|---|---|\n${rows.join('\n')}\n`;
}
fs.writeFileSync(path.join(ROOT, 'docs', 'API.md'), out);
console.log('Wrote docs/API.md');
